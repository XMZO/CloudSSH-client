export type HighlightKey = Key;

export function ht(key: Key, params: Record<string, string | number> = {}): string {
  const text = (dictionaries[getLocale()] ?? zhCN)[key] ?? zhCN[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}

/** 内置规则的说明（note 为 null 时） */
export function builtinNote(id: string): string {
  const key = `note.${id}` as Key;
  return key in zhCN ? ht(key) : id;
}


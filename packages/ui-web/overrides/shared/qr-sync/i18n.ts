export function qt(key: Key, params: Record<string, string | number> = {}): string {
  const text = (dictionaries[getLocale()] ?? zhCN)[key] ?? zhCN[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}

export function sortLabel(sort: string): string {
  if (sort === 'custom') return qt('sortCustom');
  if (sort === 'count') return qt('sortCount');
  if (sort === 'recent') return qt('sortRecent');
  return qt('sortName');
}
